/** Icons that point somewhere along the reading direction: mirrored in RTL unless `flip={false}`. */
export const DIRECTIONAL_ICONS = new Set(['arrow-right', 'arrow-left', 'arrow-up-right', 'send', 'chevron-left', 'chevron-right']);

/** Every available icon name. */
export const ICON_NAMES = [...Object.keys(STROKE), ...Object.keys(FILLED)];

export default function Icon({ name, size = 18, className, flip }) {
  const filled = Object.prototype.hasOwnProperty.call(FILLED, name);
  const shape = filled ? FILLED[name] : STROKE[name];
  if (!shape) {
    if (process.env.NODE_ENV !== 'production') {
      console.warn(`[Icon] unknown icon "${name}"`);
    }
    return null;
  }
  const mirror = flip ?? DIRECTIONAL_ICONS.has(name);

  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={filled ? 'currentColor' : 'none'}
      stroke={filled ? 'none' : 'currentColor'}
      strokeWidth={filled ? undefined : 1.6}
      strokeLinecap={filled ? undefined : 'round'}
      strokeLinejoin={filled ? undefined : 'round'}
      aria-hidden="true"
      focusable="false"
      className={cx('icon', mirror && 'icon-flip', className)}
    >
      {shape}
    </svg>
  );
}
